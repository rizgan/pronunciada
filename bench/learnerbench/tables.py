"""Markdown rendering of the learner-benchmark result JSON (bench.learnerbench.report)."""
from __future__ import annotations

from pathlib import Path

SHORT = {"pronunciada-fp32": "Pronunciada fp32", "pronunciada-int8": "Pronunciada int8",
         "openpronounce-1.1.0": "OpenPronounce 1.1.0", "openpronounce-1.1.0-student": "OpenPronounce student", "openpronounce-0.4.0": "OpenPronounce 0.4.0", "toneperfect": "TonePerfect (measured 2026-11-24/25)",
         "azure": "Azure (cached)", "lingolix": "Lingolix (cached)", "zipa-alone": "ZIPA alone (reference)", "pronunciada-nb8-sym-b128": "Pronunciada, on-device model (73 MB, candidate)", "chivox": "Chivox (sample, measured 2026-11-23)", "-duration": "-duration"}


def _f(x, d=3):
    return "–" if x is None else f"{x:.{d}f}"


def cell(e: dict) -> str:
    if "value" not in e:
        return e.get("status", "–")
    s = f"{_f(e['value'])} [{_f(e['ci'][0])}, {_f(e['ci'][1])}]"
    return s


def dcell(e: dict) -> str:
    b = e.get("base_minus")
    if not b:
        return ""
    p = b["p"]
    ps = "< 0.001" if p is not None and p < 0.001 else _f(p)
    return f"{b['value']:+.3f} [{b['ci'][0]:+.3f}, {b['ci'][1]:+.3f}], p {ps}"


def write_markdown(res: dict, path: Path) -> None:
    systems = res["systems"]
    L = ["# Learner benchmark: generated tables", "",
         f"Generated by `python -m bench.learnerbench.report` from cached outputs. 95 % intervals: speaker bootstrap, "
         f"{res['n_boot']:,} replicates. Δ = Pronunciada fp32 minus the system, paired on the same replicates, "
         "two-sided p.", ""]
    if "summaries" in res:
        L += ["## Summaries", "", "| summary | languages | speakers | items | system | value [95 % CI] | Δ (fp32 − system) |",
              "|---|---|---|---|---|---|---|"]
        for nm, s in res["summaries"].items():
            for sys_ in systems:
                e = s["systems"].get(sys_, {})
                L.append(f"| {nm} | {', '.join(s['languages'])} | {s['speakers']} | {s['items']} | {SHORT.get(sys_, sys_)} | "
                         f"{cell(e)} | {dcell(e)} |")
        L.append("")
    cur = None
    for r in res["rows"]:
        if r["test"] != cur:
            cur = r["test"]
            L += [f"## {cur} ({r['lang']}, {r['label_type']})", "",
                  "| unit | metric | items | speakers | system | value [95 % CI] | Δ (fp32 − system) |",
                  "|---|---|---|---|---|---|---|"]
        for sys_, e in r["systems"].items():
            L.append(f"| {r['unit']} | {r['metric']} | {r['n_items']} | {r['n_speakers']} | {SHORT.get(sys_, sys_)} | "
                     f"{cell(e)} | {dcell(e)} |")
    path.write_text("\n".join(L) + "\n")
